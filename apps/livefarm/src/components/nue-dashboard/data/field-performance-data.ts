// Розраховуємо розподіл на основі даних
export function getPerformanceDistribution(
  data: FieldPerformanceRow[] = fieldPerformanceData
) {
  const distribution = {
    '90%+': 0,
    '75-89%': 0,
    '60-74%': 0,
    '<60%': 0,
  };

  data.forEach((field) => {
    if (field.nue >= 90) {
      distribution['90%+']++;
    } else if (field.nue >= 75) {
      distribution['75-89%']++;
    } else if (field.nue >= 60) {
      distribution['60-74%']++;
    } else {
      distribution['<60%']++;
    }
  });

  return distribution;
}
