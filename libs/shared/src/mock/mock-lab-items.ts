export const getLabOrderByTaskId = (
  taskId: string,
  taskData?: any
): LabItem | null => {
  if (taskData && taskData.labOrderNumber) {
    return {
      id: `lab-${taskId}`,
      labName: 'Lab №1',
      client: {
        name: taskData.farmer_name || 'Unknown',
        surname: '',
        avatarSrc: undefined,
      },
      farm: taskData.farms || 'Unknown Farm',
      taskId: taskId,
      labOrderNo: taskData.labOrderNumber,
      samples: taskData.no_of_samples || 0,
      sampleDate: taskData.date || '',
      sentDate: taskData.labSentDate || '',
      receivedDate: taskData.labReceivedDate || '',
      status: taskData.labStatus || 'pending',
      hasResults: false,
      updatedAt: new Date().toISOString(),
      type: 'Soil',
    };
  }

  return mockLabItems.find((item) => item.taskId === taskId) || null;
};

